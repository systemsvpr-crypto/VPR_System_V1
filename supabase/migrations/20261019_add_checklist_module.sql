CREATE OR REPLACE FUNCTION public.checklist_maint_repair_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.checklist_maint_repair_fill_defaults()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  doer text;
  u_dept text;
BEGIN
  IF TG_TABLE_NAME = 'repair_tasks' THEN
    doer := NEW.assigned_person;
    IF NEW.status IS NULL OR lower(NEW.status) = 'pending' THEN
      NEW.status := 'Pending';
    END IF;
    IF NEW.task_start_date IS NULL THEN
      NEW.task_start_date := COALESCE(NEW.created_at, now());
    END IF;
  ELSE
    doer := NEW.name;
    IF NEW.planned_date IS NULL THEN
      NEW.planned_date := NEW.task_start_date;
    END IF;
  END IF;

  IF doer IS NOT NULL AND NEW.department IS NULL THEN
    BEGIN
      EXECUTE 'SELECT department::text FROM public.checklist_users WHERE user_name = $1 LIMIT 1'
        INTO u_dept USING doer;
      NEW.department := COALESCE(NEW.department, u_dept);
    EXCEPTION WHEN others THEN
      NULL;
    END;
  END IF;
  RETURN NEW;
END;
$$;

