-- Checklist module (task management: checklist / delegation /
-- maintenance / repair tasks, approvals, holidays, employees).
--
-- Architecture:
-- 1. Identity & Credentials: Uses VPR's existing `public.users` table as the
--    single source of truth (full_name, username, email, phone, role, designation, profile_picture).
-- 2. Checklist Operational Data: Stored in `public.checklist_user_profiles`
--    (department, reporting manager, day off, leaves, can_self_assign).
-- 3. Unified View: `public.checklist_users` joins `public.users` with
--    `public.checklist_user_profiles` so checklist frontend queries work seamlessly.
-- 4. Tasks & Operations: Creates purely additive task tables, buckets, and triggers.
-- Every statement is guarded (IF NOT EXISTS / OR REPLACE / ON CONFLICT), so
-- the file is idempotent and safe to re-run.

-- ═══════════════════════ 1. Employees, settings, calendars

-- ---------------------------------------------------------------------------
-- checklist_user_profiles — checklist-specific operational employee data.
-- General user info (full_name, username, password, email, phone, role,
-- designation, profile_picture) is fetched directly from VPR's `public.users`
-- table. This table ONLY stores checklist module operational fields:
-- department, reporting manager, day off, and leave dates.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.checklist_user_profiles (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          uuid NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE,
  department       text,
  user_access      text,
  page_access      text,
  reported_by      text,
  day_off          text,
  leave_date       date,
  leave_end_date   date,
  remark           text,
  can_self_assign  boolean NOT NULL DEFAULT false,
  employee_id      text,
  location         text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS checklist_user_profiles_user_id_idx     ON public.checklist_user_profiles (user_id);
CREATE INDEX IF NOT EXISTS checklist_user_profiles_department_idx  ON public.checklist_user_profiles (department);
CREATE INDEX IF NOT EXISTS checklist_user_profiles_reported_by_idx ON public.checklist_user_profiles (reported_by);
CREATE INDEX IF NOT EXISTS checklist_user_profiles_employee_id_idx ON public.checklist_user_profiles (employee_id);

-- ---------------------------------------------------------------------------
-- checklist_users — Unified View.
-- Joins VPR's `public.users` (source of truth for identity) with
-- `public.checklist_user_profiles` (checklist operational settings).
-- The checklist module's frontend queries this view transparently.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.checklist_users AS
SELECT
  p.id,
  u.user_id                                           AS vpr_user_id,
  COALESCE(NULLIF(TRIM(u.full_name), ''), u.username) AS user_name,
  u.email                                             AS email_id,
  u.phone_number                                      AS number,
  u.designation                                       AS "Designation",
  u.profile_picture                                   AS profile_image,
  CASE
    WHEN UPPER(u.role) IN ('SUPER ADMIN', 'SUPER_ADMIN', 'SUPERADMIN') THEN 'ADMINISTRATOR'
    WHEN UPPER(u.role) LIKE '%ADMIN%' THEN 'admin'
    ELSE 'user'
  END                                                 AS role,
  CASE WHEN u.is_active THEN 'active' ELSE 'inactive' END AS status,
  p.department,
  p.user_access,
  p.page_access,
  p.reported_by,
  p.day_off,
  p.leave_date,
  p.leave_end_date,
  p.remark,
  COALESCE(p.can_self_assign, false)                  AS can_self_assign,
  p.employee_id,
  p.location,
  u.created_at
FROM public.users u
LEFT JOIN public.checklist_user_profiles p ON u.user_id = p.user_id;

GRANT ALL ON TABLE public.checklist_users TO anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Updatable View Trigger:
-- Allows updating employee department, leaves, day_off, etc.,
-- writing directly to checklist_user_profiles.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_checklist_users_upsert()
RETURNS trigger AS $$
DECLARE
  target_user_id uuid;
BEGIN
  IF TG_OP = 'INSERT' THEN
    target_user_id := NEW.vpr_user_id;
    IF target_user_id IS NULL THEN
      SELECT user_id INTO target_user_id FROM public.users
      WHERE lower(COALESCE(NULLIF(TRIM(full_name), ''), username)) = lower(NEW.user_name) LIMIT 1;
    END IF;

    IF target_user_id IS NOT NULL THEN
      INSERT INTO public.checklist_user_profiles (
        user_id, department, user_access, page_access, reported_by, day_off, leave_date, leave_end_date, remark, can_self_assign, employee_id, location
      ) VALUES (
        target_user_id, NEW.department, NEW.user_access, NEW.page_access, NEW.reported_by, NEW.day_off, NEW.leave_date, NEW.leave_end_date, NEW.remark, COALESCE(NEW.can_self_assign, false), NEW.employee_id, NEW.location
      )
      ON CONFLICT (user_id) DO UPDATE SET
        department = COALESCE(EXCLUDED.department, checklist_user_profiles.department),
        user_access = COALESCE(EXCLUDED.user_access, checklist_user_profiles.user_access),
        page_access = COALESCE(EXCLUDED.page_access, checklist_user_profiles.page_access),
        reported_by = COALESCE(EXCLUDED.reported_by, checklist_user_profiles.reported_by),
        day_off = COALESCE(EXCLUDED.day_off, checklist_user_profiles.day_off),
        leave_date = EXCLUDED.leave_date,
        leave_end_date = EXCLUDED.leave_end_date,
        remark = EXCLUDED.remark,
        can_self_assign = COALESCE(EXCLUDED.can_self_assign, checklist_user_profiles.can_self_assign),
        employee_id = COALESCE(EXCLUDED.employee_id, checklist_user_profiles.employee_id),
        location = COALESCE(EXCLUDED.location, checklist_user_profiles.location),
        updated_at = now();
    END IF;
    RETURN NEW;

  ELSIF TG_OP = 'UPDATE' THEN
    target_user_id := COALESCE(NEW.vpr_user_id, OLD.vpr_user_id);
    IF target_user_id IS NULL AND OLD.user_name IS NOT NULL THEN
      SELECT user_id INTO target_user_id FROM public.users
      WHERE lower(COALESCE(NULLIF(TRIM(full_name), ''), username)) = lower(OLD.user_name) LIMIT 1;
    END IF;

    IF target_user_id IS NOT NULL THEN
      INSERT INTO public.checklist_user_profiles (
        user_id, department, user_access, page_access, reported_by, day_off, leave_date, leave_end_date, remark, can_self_assign, employee_id, location
      ) VALUES (
        target_user_id, NEW.department, NEW.user_access, NEW.page_access, NEW.reported_by, NEW.day_off, NEW.leave_date, NEW.leave_end_date, NEW.remark, COALESCE(NEW.can_self_assign, false), NEW.employee_id, NEW.location
      )
      ON CONFLICT (user_id) DO UPDATE SET
        department = COALESCE(EXCLUDED.department, checklist_user_profiles.department),
        user_access = COALESCE(EXCLUDED.user_access, checklist_user_profiles.user_access),
        page_access = COALESCE(EXCLUDED.page_access, checklist_user_profiles.page_access),
        reported_by = COALESCE(EXCLUDED.reported_by, checklist_user_profiles.reported_by),
        day_off = COALESCE(EXCLUDED.day_off, checklist_user_profiles.day_off),
        leave_date = EXCLUDED.leave_date,
        leave_end_date = EXCLUDED.leave_end_date,
        remark = EXCLUDED.remark,
        can_self_assign = COALESCE(EXCLUDED.can_self_assign, checklist_user_profiles.can_self_assign),
        employee_id = COALESCE(EXCLUDED.employee_id, checklist_user_profiles.employee_id),
        location = COALESCE(EXCLUDED.location, checklist_user_profiles.location),
        updated_at = now();
    END IF;
    RETURN NEW;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_checklist_users_upsert ON public.checklist_users;
CREATE TRIGGER trigger_checklist_users_upsert
  INSTEAD OF INSERT OR UPDATE ON public.checklist_users
  FOR EACH ROW EXECUTE FUNCTION public.handle_checklist_users_upsert();

-- ---------------------------------------------------------------------------
-- Seed existing VPR users into checklist_user_profiles
