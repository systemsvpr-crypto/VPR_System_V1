-- ═══════════════════════ 2. Checklist and delegation tasks
-- Additive only: new tables, views, trigger functions, indexes, permissive RLS.
--
-- Conventions the pages rely on:
--   * checklist and delegation keep id === task_id.
--   * checklist/delegation task_start_date + planned_date are `timestamp` (no zone).
--   * Everything else time-like is timestamptz.
--   * enable_reminder / require_attachment are 'yes' / 'no' text.
--   * admin_done false = submitted & awaiting approval; true = approved.

-- ─────────────────────────────────────────────────────────────────────────
-- Trigger functions
-- ─────────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.checklist_tasks_sync_task_id()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.task_id := COALESCE(NEW.task_id, NEW.id);
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.checklist_tasks_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

