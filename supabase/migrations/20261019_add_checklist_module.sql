INSERT INTO public.checklist_user_profiles (user_id)
SELECT user_id FROM public.users
ON CONFLICT (user_id) DO NOTHING;

-- ---------------------------------------------------------------------------
-- Auto-create profile for any new VPR user
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sync_vpr_user_to_checklist()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.checklist_user_profiles (user_id)
  VALUES (NEW.user_id)
  ON CONFLICT (user_id) DO NOTHING;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_sync_vpr_user_to_checklist ON public.users;
CREATE TRIGGER trigger_sync_vpr_user_to_checklist
  AFTER INSERT ON public.users
  FOR EACH ROW EXECUTE FUNCTION public.sync_vpr_user_to_checklist();

